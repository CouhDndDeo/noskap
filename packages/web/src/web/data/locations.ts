export type LocationKind =
  | "city"
  | "capital"
  | "citadel"
  | "mountain"
  | "forest"
  | "cursed"
  | "wild";

export type Location = {
  id: string;
  /** X в пикселях исходной карты (4146×2354) */
  x: number;
  /** Y в пикселях, origin — левый нижний угол (как в старом locations.json) */
  y: number;
  kind: LocationKind;
  name: string;
  /** Короткая строка для списка и подписи */
  summary: string;
  /** Длинный лор в markdown */
  lore: string;
  tags: string[];
  /** Видно только в режиме ГМ (?gm=1) */
  hidden?: boolean;
  /** Заметки, которые видит только ГМ */
  gmNotes?: string;
  /** Путь к арту в /images/locations/, необязателен */
  art?: string;
};

